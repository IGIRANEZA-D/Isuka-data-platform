// 7. Report what's in public/
function countFiles(dir) {
  let count = 0;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) count += countFiles(path.join(dir, entry.name));
    else count++;
  }
  return count;
}

const totalFiles = countFiles(publicDir);
console.log(`[build-public-dir] Done. ${totalFiles} files in public/.`);
