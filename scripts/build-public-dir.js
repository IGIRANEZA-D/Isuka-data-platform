#!/usr/bin/env node
/**
 * build-public-dir.js
 *
 * Assembles the `public/` directory that Vercel serves as static CDN files.
 * Copies:
 *   - frontend/dist/* -> public/          (Vite-built dashboard assets)
 *   - www/*.html, www/*.css, www/*.js,
 *     www/*.png, www/*.jpg, www/*.svg     -> public/   (landing page assets)
 *   - 404.html and 500.html               -> public/   (error pages)
 *
 * The Express backend serves HTML pages for /dashboard/*, /account/*, /admin/*,
 * /  — those requests are rewritten to api/index.js by vercel.json, so we do NOT
 * put the HTML in public/ (that would cause static 200s to override the Express
 * routes). Only the landing page static assets (CSS/JS/images) go in public/.
 *
 * Data Library static CSV/ZIP files (generated by build-static-exports.js) are
 * copied to public/downloads/.
 */

'use strict';

const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const publicDir = path.join(root, 'public');

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

function copyFile(src, dest) {
  ensureDir(path.dirname(dest));
  fs.copyFileSync(src, dest);
}

function copyDirRecursive(src, dest, filter) {
  ensureDir(dest);
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const srcPath = path.join(src, entry.name);
    const destPath = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      copyDirRecursive(srcPath, destPath, filter);
    } else if (!filter || filter(entry.name, srcPath)) {
      copyFile(srcPath, destPath);
    }
  }
}

// Clean and recreate public/
if (fs.existsSync(publicDir)) {
  fs.rmSync(publicDir, { recursive: true, force: true });
}
ensureDir(publicDir);

// 1. Copy Vite build output (frontend/dist -> public/)
const frontendDist = path.join(root, 'frontend', 'dist');
if (fs.existsSync(frontendDist)) {
  copyDirRecursive(frontendDist, publicDir);
  console.log('[build-public-dir] Copied frontend/dist -> public/');
} else {
  console.warn('[build-public-dir] WARNING: frontend/dist not found; run npm run build:frontend first.');
}

// 2. Copy the source pages and shared assets to their stable CDN paths.
const frontendDir = path.join(root, 'frontend');
const pagePaths = {
  'index.html': 'dashboard/index.html',
  'land-crops.html': 'dashboard/land-crops/index.html',
  'climate-risk.html': 'dashboard/climate-risk/index.html',
  'inputs-practices.html': 'dashboard/inputs-practices/index.html',
  'district-explorer.html': 'dashboard/district-explorer/index.html',
  'forecasting.html': 'dashboard/forecasting/index.html',
  'forecasting-analysis.html': 'dashboard/forecasting/analysis/index.html',
  'loss-planner.html': 'dashboard/loss-planner/index.html',
  'account-login.html': 'account/login.html',
  'account-signup.html': 'account/signup.html',
  'account-setup.html': 'account/setup.html',
  'account-dashboard.html': 'account/dashboard.html',
  'account-my-farm.html': 'account/my-farm.html',
  'account-assistant.html': 'account/assistant.html',
  'account-alerts.html': 'account/alerts.html',
  'account-settings.html': 'account/settings.html',
  'admin-login.html': 'admin/login.html',
  'admin-dashboard.html': 'admin/index.html',
  'admin-datasets.html': 'admin/datasets.html',
  'admin-upload.html': 'admin/upload.html',
  'admin-reports.html': 'admin/reports.html'
};
for (const [sourceName, outputName] of Object.entries(pagePaths)) {
  const sourcePath = path.join(frontendDir, sourceName);
  if (fs.existsSync(sourcePath)) copyFile(sourcePath, path.join(publicDir, outputName));
}
for (const entry of fs.readdirSync(frontendDir, { withFileTypes: true })) {
  if (entry.isFile() && /\.(css|js)$/.test(entry.name)) {
    copyFile(path.join(frontendDir, entry.name), path.join(publicDir, entry.name));
    copyFile(path.join(frontendDir, entry.name), path.join(publicDir, 'dashboard', entry.name));
  }
}
for (const directory of ['assistant', 'fixtures', 'lib']) {
  const sourcePath = path.join(frontendDir, directory);
  if (fs.existsSync(sourcePath)) copyDirRecursive(sourcePath, path.join(publicDir, directory));
}
const landingHtml = path.join(root, 'www', 'landing.html');
if (fs.existsSync(landingHtml)) copyFile(landingHtml, path.join(publicDir, 'index.html'));
console.log('[build-public-dir] Copied routed HTML pages and frontend assets to CDN paths.');

// 2. Copy landing page static assets from www/ (NOT the HTML; Express serves that)
const wwwDir = path.join(root, 'www');
const wwwStaticExtensions = new Set(['.css', '.js', '.png', '.jpg', '.jpeg', '.webp', '.gif', '.svg', '.ico', '.woff', '.woff2', '.ttf', '.eot']);
const wwwExcludeDirs = new Set(['Datasets(2020-2025)', 'Whole Dashboard', 'node_modules']);

function copyWwwStatics(src, dest) {
  ensureDir(dest);
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    if (wwwExcludeDirs.has(entry.name)) continue;
    const srcPath = path.join(src, entry.name);
    const destPath = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      copyWwwStatics(srcPath, destPath);
    } else {
      const ext = path.extname(entry.name).toLowerCase();
      if (wwwStaticExtensions.has(ext)) {
        copyFile(srcPath, destPath);
      }
    }
  }
}

copyWwwStatics(wwwDir, publicDir);
copyWwwStatics(wwwDir, path.join(publicDir, 'assets'));
copyFile(path.join(wwwDir, 'ISUKA_BOT_Animated_No_Status.html'), path.join(publicDir, 'www', 'isuka-bot-animated-no-status.html'));
console.log('[build-public-dir] Copied www/ static assets (CSS/JS/images) -> public/');

// 3. Copy frontend/data directory (landing-art.json, etc.)
const frontendData = path.join(root, 'frontend', 'data');
if (fs.existsSync(frontendData)) {
  copyDirRecursive(frontendData, path.join(publicDir, 'data'));
  console.log('[build-public-dir] Copied frontend/data -> public/data');
}

// 4. Publish generated static Data Library files directly from verified artifacts.
const artifactDownloads = path.join(root, 'backend', 'data', 'dist', 'downloads');
if (fs.existsSync(artifactDownloads)) {
  copyDirRecursive(artifactDownloads, path.join(publicDir, 'downloads'));
  console.log('[build-public-dir] Copied committed data exports -> public/downloads/');
}

